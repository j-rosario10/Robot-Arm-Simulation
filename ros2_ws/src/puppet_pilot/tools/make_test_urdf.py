"""Strip a flattened URDF down to its kinematic skeleton for hermetic tests.

Removes every <visual>, <collision> and <ros2_control> element, leaving links
(with inertials), joints and transforms. The result has no mesh file
references, so the FK validation tests can load it in PyBullet on any machine
without a built workspace.

Regenerate after any robot-model change:

    xacro <...>/ur5e_robotiq_2f_85_urdf.xacro > /tmp/ur5e_robotiq.urdf
    python tools/make_test_urdf.py --in /tmp/ur5e_robotiq.urdf \
        --out tests/data/ur5e_robotiq_kinematic.urdf
"""

from __future__ import annotations

import argparse
import xml.etree.ElementTree as ET
from pathlib import Path


def strip_geometry(tree: ET.ElementTree) -> None:
    root = tree.getroot()
    for parent in root.iter():
        for tag in ("visual", "collision", "ros2_control"):
            for child in parent.findall(tag):
                parent.remove(child)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--in", dest="input", required=True)
    parser.add_argument("--out", dest="output", required=True)
    args = parser.parse_args()

    tree = ET.parse(args.input)
    strip_geometry(tree)
    out = Path(args.output)
    out.parent.mkdir(parents=True, exist_ok=True)
    header = (
        "<!-- Generated by tools/make_test_urdf.py from the colcon-built\n"
        "     ur5e_robotiq_2f_85 xacro. Kinematic skeleton only (no geometry);\n"
        "     used by the FK validation tests. Do not edit by hand. -->\n"
    )
    body = ET.tostring(tree.getroot(), encoding="unicode")
    out.write_text('<?xml version="1.0"?>\n' + header + body, encoding="utf-8")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
