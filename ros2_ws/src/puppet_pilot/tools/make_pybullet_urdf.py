"""Generate the PyBullet-loadable robot URDF from the colcon-built xacro.

PyBullet resolves neither ``package://`` nor ``file://`` URIs, so the flattened
URDF that ROS is happy with cannot be loaded directly. This tool rewrites the
mesh paths to absolute filesystem paths and caches the result in
``generated/`` so the simulator starts without needing a sourced ROS
environment at runtime.

Regenerate after any change to the robot model:

    source /opt/ros/jazzy/setup.bash
    source <workspace>/install/setup.bash
    python tools/make_pybullet_urdf.py
"""

from __future__ import annotations

import argparse
import re
import subprocess
from pathlib import Path

_PACKAGES = ["ur_description", "robotiq_description", "ur_robotiq_description"]


def _package_share(package: str) -> Path:
    """Locate a package's installed share directory via the ROS 2 CLI."""
    prefix = subprocess.run(
        ["ros2", "pkg", "prefix", package],
        capture_output=True, text=True, check=True,
    ).stdout.strip()
    return Path(prefix) / "share" / package


def main() -> None:
    package_root = Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--out",
        default=str(package_root / "generated" / "ur5e_robotiq_pybullet.urdf"),
    )
    args = parser.parse_args()

    share = {name: _package_share(name) for name in _PACKAGES}
    xacro_file = share["ur_robotiq_description"] / "urdf" / "ur5e_robotiq_2f_85_urdf.xacro"

    flat = subprocess.run(
        ["xacro", str(xacro_file)], capture_output=True, text=True, check=True
    ).stdout

    for name, path in share.items():
        flat = flat.replace(f"package://{name}/", f"{path}/")
    flat = flat.replace("file://", "")

    leftover = re.findall(r"package://[\w/.-]+", flat)
    if leftover:
        raise RuntimeError(f"unresolved package URIs remain: {sorted(set(leftover))[:5]}")

    provenance = (
        "<!-- Generated by tools/make_pybullet_urdf.py from the colcon-built\n"
        "     ur5e_robotiq_2f_85 xacro, with mesh URIs rewritten to absolute\n"
        "     paths for PyBullet. Do not edit by hand. -->\n"
    )
    # The XML declaration must stay the very first thing in the file, so the
    # provenance comment goes after it, not before.
    declaration = re.match(r"\s*<\?xml[^>]*\?>\s*", flat)
    if declaration:
        flat = declaration.group(0).strip() + "\n" + provenance + flat[declaration.end():]
    else:
        flat = provenance + flat

    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(flat, encoding="utf-8")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
